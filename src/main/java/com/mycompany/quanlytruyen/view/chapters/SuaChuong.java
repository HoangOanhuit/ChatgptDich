    private void setChapter(Chapter chapter) {
        this.editingChapter = chapter;
        if (chapter == null) {
            return;
        }
        txtNo.setText(chapter.getChapterNumber() != null ? chapter.getChapterNumber().toString() : "");
        txtName.setText(chapter.getChapterTitle());
        chapterContent.setText(chapter.getContent());
        if (chapter.getBetaStatus() != null) {
            betaStatus.setSelectedItem(chapter.getBetaStatus().getDisplayName());
        }
        if (chapter.getBookId() != null) {
            String prefix = chapter.getBookId() + " -";
            for (int i = 0; i < book_tiltle.getItemCount(); i++) {
                String item = book_tiltle.getItemAt(i);
                if (item.startsWith(prefix)) {
                    book_tiltle.setSelectedIndex(i);
                    break;
                }
            }
        }
    }

    private void loadCombos() {
        betaStatus.removeAllItems();
        for (BetaStatus bs : BetaStatus.values()) {
            betaStatus.addItem(bs.getDisplayName());
        }
        book_tiltle.removeAllItems();
        if (bookDao != null) {
            try {
                List<Book> books = bookDao.getAllBooks();
                for (Book b : books) {
                    book_tiltle.addItem(b.getId() + " - " + b.getTitle());
                }
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(this, "Lỗi tải truyện: " + ex.getMessage());
            }
        }
    }

