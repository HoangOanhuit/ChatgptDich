    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        if (editingChapter == null || chapterDao == null) {
            return;
        }
        try {
            String bookItem = (String) book_tiltle.getSelectedItem();
            long bookId = editingChapter.getBookId();
            if (bookItem != null) {
                int dash = bookItem.indexOf(" - ");
                if (dash > 0) {
                    bookId = Long.parseLong(bookItem.substring(0, dash));
                }
            }
            int number = Integer.parseInt(txtNo.getText().trim());
            String title = txtName.getText().trim();
            String content = chapterContent.getText();
            String betaName = (String) betaStatus.getSelectedItem();
            BetaStatus bs = BetaStatus.fromDisplayName(betaName);

            editingChapter.setBookId(bookId);
            editingChapter.setChapterNumber(number);
            editingChapter.setChapterTitle(title);
            editingChapter.setContent(content);
            editingChapter.setBetaStatus(bs);

            chapterDao.updateChapter(editingChapter);
            JOptionPane.showMessageDialog(this, "Cập nhật thành công");
            if (parentPanel != null) {
                parentPanel.reloadChapters();
            }
            dispose();
        } catch (SQLException | NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Lỗi: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnEditActionPerformed

