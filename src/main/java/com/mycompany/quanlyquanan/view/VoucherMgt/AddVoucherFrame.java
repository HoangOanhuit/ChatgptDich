    private void submitButtonActionPerformed(java.awt.event.ActionEvent evt) {
        try {
            String vcCode = vcCodeTextField.getText().trim();
            String description = descriptionTextArea.getText().trim();
            String percentage = percentageTextField.getText().trim();
            String quantity = quantityTextField.getText().trim();
            LocalDate startDateLocale = startDateField.getDate();
            LocalDate endDateLocale = endDateField.getDate();


            // Kiểm tra các trường bắt buộc
            if (vcCode.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Voucher Code không được để trống", "Lỗi", JOptionPane.ERROR_MESSAGE);
                vcCodeTextField.requestFocus();
                return;
            }

            if (description.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Mô tả không được để trống", "Lỗi", JOptionPane.ERROR_MESSAGE);
                descriptionTextArea.requestFocus();
                return;
            }

            if (percentage.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Phần trăm giảm giá không được để trống", "Lỗi", JOptionPane.ERROR_MESSAGE);
                percentageTextField.requestFocus();
                return;
            }

            if (!percentage.matches("\\d+(\\.\\d+)?")) {
                JOptionPane.showMessageDialog(this, "Phần trăm giảm giá phải là số", "Lỗi", JOptionPane.ERROR_MESSAGE);
                percentageTextField.requestFocus();
                return;
            }

            if (quantity.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Số lượng không được để trống", "Lỗi", JOptionPane.ERROR_MESSAGE);
                quantityTextField.requestFocus();
                return;
            }

            if (!quantity.matches("\\d+")) {
                JOptionPane.showMessageDialog(this, "Số lượng phải là số nguyên", "Lỗi", JOptionPane.ERROR_MESSAGE);
                quantityTextField.requestFocus();
                return;
            }

            Double percentageDouble = Double.parseDouble(percentage);
            Integer quantityInteger = Integer.parseInt(quantity);
            if (percentageDouble <= 0 || percentageDouble > 100) {
                JOptionPane.showMessageDialog(this, "Phần trăm giảm giá phải là số dương và không quá 100", "Lỗi", JOptionPane.ERROR_MESSAGE);
                percentageTextField.requestFocus();
                return;
            }
            if (quantityInteger <= 0) {
                JOptionPane.showMessageDialog(this, "Số lượng phải là số nguyên dương", "Lỗi", JOptionPane.ERROR_MESSAGE);
                quantityTextField.requestFocus();
                return;
            }

            if (startDateLocale == null) {
                JOptionPane.showMessageDialog(this, "Ngày bắt đầu không được để trống", "Lỗi", JOptionPane.ERROR_MESSAGE);
                startDateField.requestFocus();
                return;
            }

            if (endDateLocale == null) {
                JOptionPane.showMessageDialog(this, "Ngày kết thúc không được để trống", "Lỗi", JOptionPane.ERROR_MESSAGE);
                endDateField.requestFocus();
                return;
            }

            if (startDateLocale.isAfter(endDateLocale)) {
                JOptionPane.showMessageDialog(this, "Ngày bắt đầu phải trước ngày kết thúc", "Lỗi", JOptionPane.ERROR_MESSAGE);
                startDateField.requestFocus();
                return;
            }

            // Kiểm tra trùng lặp mã voucher
            if (vcController.isVoucherCodeExists(vcCode)) {
                JOptionPane.showMessageDialog(this, "Voucher code đã tồn tại", "Lỗi", JOptionPane.ERROR_MESSAGE);
                vcCodeTextField.requestFocus();
                return;
            }

            // Convert sang java.util.Date (nếu Voucher dùng Date)
            Date startDate = Date.from(startDateLocale.atStartOfDay(ZoneId.systemDefault()).toInstant());
            Date endDate = Date.from(endDateLocale.atStartOfDay(ZoneId.systemDefault()).toInstant());

            // Nếu không có lỗi, tạo mới voucher
            voucher.setVoucherCode(vcCode);
            voucher.setDescription(description);
            voucher.setPercentage(percentageDouble);
            voucher.setQuantity(quantityInteger);
            voucher.setStartDate(startDate);
            voucher.setEndDate(endDate);

            vcController.addVoucher(voucher);

            //[Todo] thêm callback để load lại table voucher
            if (onAddSuccess != null) {
                onAddSuccess.run();
            }

            this.dispose();
            JOptionPane.showMessageDialog(AddVoucherFrame.this,
                    "Tạo mới voucher thành công! \n Mã voucher: " + voucher.getVoucherCode(),
                    "Thành công",
                    JOptionPane.INFORMATION_MESSAGE);


        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                    "Lỗi: " + e.getMessage(),
                    "Lỗi",
                    JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }

