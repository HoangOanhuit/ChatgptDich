    private void loadDishes() {
        dishes.clear();
        dishes.addAll(recipeController.getAvailableDishes());
        DefaultComboBoxModel model = new DefaultComboBoxModel(dishes.toArray());
        cboDish.setModel(model);
    }

    private void loadMaterials() {
        materials.clear();
        materials.addAll(recipeController.getActiveMaterials());
        DefaultComboBoxModel model = new DefaultComboBoxModel(materials.toArray());
        ipMaterial.setModel(model);
        ipMaterial.setRenderer(new DefaultListCellRenderer() {
            @Override
            public java.awt.Component getListCellRendererComponent(JList<?> list, Object value, int index, boolean isSelected, boolean cellHasFocus) {
                super.getListCellRendererComponent(list, value, index, isSelected, cellHasFocus);
                if (value instanceof Material m) {
                    setText(m.getName());
                }
                return this;
            }
        });
    }

    private void setupListeners() {
        ipMaterial.addActionListener(e -> updateMaterialInfo());
        ipQuantity.getDocument().addDocumentListener(new DocumentListener() {
            @Override
            public void insertUpdate(DocumentEvent e) {
                updateTotalCost();
            }

            @Override
            public void removeUpdate(DocumentEvent e) {
                updateTotalCost();
            }

            @Override
            public void changedUpdate(DocumentEvent e) {
                updateTotalCost();
            }
        });
    }

    private void updateMaterialInfo() {
        Material m = (Material) ipMaterial.getSelectedItem();
        if (m != null) {
            ipUnit.setText(m.getUnit());
            lblMaterialPrice.setText(formatPrice(m.getPricePerUnit()) + "/đơn vị");
        } else {
            ipUnit.setText("");
            lblMaterialPrice.setText("");
        }
        updateTotalCost();
    }

    private void updateTotalCost() {
        Material m = (Material) ipMaterial.getSelectedItem();
        if (m == null) {
            lblTotalCost.setText("");
            return;
        }
        try {
            BigDecimal qty = new BigDecimal(ipQuantity.getText().trim());
            if (qty.compareTo(BigDecimal.ZERO) < 0) {
                lblTotalCost.setText("");
                return;
            }
            BigDecimal total = m.getPricePerUnit().multiply(qty);
            lblTotalCost.setText(formatPrice(total));
        } catch (Exception e) {
            lblTotalCost.setText("");
        }
    }

    private String formatPrice(BigDecimal price) {
        return String.format("%,.0f VNĐ", price);
    }


