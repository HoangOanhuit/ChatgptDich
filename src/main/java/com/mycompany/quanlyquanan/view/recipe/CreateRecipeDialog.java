    private void bntAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bntAddActionPerformed
        Material selectedMaterial = (Material) ipMaterial.getSelectedItem();
        Dish selectedDish = (Dish) cboDish.getSelectedItem();
        if (selectedMaterial == null || selectedDish == null) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn món ăn và nguyên liệu", "Lỗi", JOptionPane.ERROR_MESSAGE);
            return;
        }
        BigDecimal quantity;
        try {
            quantity = new BigDecimal(ipQuantity.getText().trim());
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Số lượng không hợp lệ", "Lỗi", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (recipeController.createWithValidation(selectedDish.getId(), selectedMaterial.getId(), quantity)) {
            if (parentPanel != null) {
                parentPanel.loadRecipes();
            }
            dispose();
        }
    }//GEN-LAST:event_bntAddActionPerformed

