    private void btnOrderSearchMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnOrderSearchMouseClicked

        // TODO add your handling code here:
        String keyword = dSearchText.getText().trim();
        selectedRow = -1;
        if (keyword.isEmpty()) {
            createInitalDishPanel(); // Nếu rỗng thì load lại toàn bộ
        } else {
            DishController dc = new DishController();
                keyword = "%"+keyword+"%";
                List<Dish> dl = dc.getBySearch(keyword);
                createDishPanelSearch(dl);
        }
    }//GEN-LAST:event_btnOrderSearchMouseClicked

