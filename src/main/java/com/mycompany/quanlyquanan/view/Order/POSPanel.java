    private void showOrderConfirmationDialog(int orderId, Map<Dish, Integer> dishMap) {
        JDialog dialog = new JDialog((JFrame) SwingUtilities.getWindowAncestor(this), "Đơn hàng đã tạo", true);
        dialog.setLayout(new BorderLayout(10, 10));
        BigDecimal total = BigDecimal.ZERO;

        // Header
        JLabel header = new JLabel("Đơn hàng #" + orderId + " đã được tạo thành công");
        header.setFont(new Font("Arial", Font.BOLD, 16));
        header.setHorizontalAlignment(SwingConstants.CENTER);
        dialog.add(header, BorderLayout.NORTH);

        // Table of dishes
        String[] columns = { "Tên món", "Số lượng", "Đơn giá", "Thành tiền" };
        DefaultTableModel model = new DefaultTableModel(columns, 0);

        for (Map.Entry<Dish, Integer> entry : dishMap.entrySet()) {
            Dish dish = entry.getKey();
            int qty = entry.getValue();
            BigDecimal price = dish.getPrice();
            BigDecimal amount = price.multiply(BigDecimal.valueOf(qty));
            total = total.add(amount);

            model.addRow(new Object[] {
                dish.getName(),
                qty,
                String.format("%,.0f₫", price),
                String.format("%,.0f₫", amount)
            });
            
            
        }
        
        model.addRow(new Object[] {
                "Tổng tiền",
                "",
                "",
                String.format("%,.0f₫", total)
            });

        JTable table = new JTable(model);
        table.setEnabled(false);
        table.setRowHeight(24);
        JScrollPane scrollPane = new JScrollPane(table);
        dialog.add(scrollPane, BorderLayout.CENTER);

        // Buttons
        JPanel buttonPanel = new JPanel(new FlowLayout(FlowLayout.CENTER, 20, 10));
        JButton stayBtn = new JButton("OK");


        stayBtn.addActionListener(e -> {
            dialog.dispose();
            clearDTable();
            dishMap.clear();
        });

        buttonPanel.add(stayBtn);
        dialog.add(buttonPanel, BorderLayout.SOUTH);

        dialog.setSize(500, 400);
        dialog.setLocationRelativeTo(this);
        dialog.setVisible(true);
    }
    
