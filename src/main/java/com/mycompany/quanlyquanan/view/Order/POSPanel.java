    private void confirmOrder() {
        OrderController oc = new OrderController();
        Order o = new Order();
        o.setTable_id(this.tableId);
        // Cập nhật trạng thái của table 
        new Thread(() -> {
            if (this.tableId != 0) {
                TableController tc = new TableController();
                Table t = tc.getTableById(o.getTable_id());
                t.setStatus("serving");
                tc.updateTable(t);
            }
        }).start(); 
        
        
        BigDecimal total = BigDecimal.ZERO;
        for (Map.Entry<Dish, Integer> entry : dishMap.entrySet()) {
            Dish dish = entry.getKey();
            int qty = entry.getValue();
            BigDecimal price = dish.getPrice();
            BigDecimal amount = price.multiply(BigDecimal.valueOf(qty));
            total = total.add(amount);
        }
        o.setTotal_amount(total);
        
        int emId = currentEm == null ? 0 : currentEm.getId();
        o.setEmployee_id(emId); // Phải cập nhật id nhân viên ở đây
        OrderController os = new OrderController();
        // Bước 1. Tạo Order khi bấm Confirm
        oc.create(o);
        Order order = os.getLastestOrder();
        newOrderId = order.getId();
            
        // Bước 2. Tạo order_items của order vừa trên
        addOrderItemToDB(newOrderId);
    }
    
    // Tạo các orderItem cho order vừa tạo
    private void addOrderItemToDB(int orderId) {
        List<OrderItem> oil = createOrderItems(orderId);
        OrderItemController oic = new OrderItemController();
        for(OrderItem oi : oil) {
            oic.create(oi);
        }
    }
    
    private List<OrderItem> createOrderItems(int orderId) {
        List<OrderItem> orderItems = new ArrayList<>();

        for (Map.Entry<Dish, Integer> entry : dishMap.entrySet()) {
            Dish dish = entry.getKey();
            int quantity = entry.getValue();

            OrderItem item = new OrderItem(orderId, dish.getId(), quantity);
            orderItems.add(item);
        }

        return orderItems;
    }
    
