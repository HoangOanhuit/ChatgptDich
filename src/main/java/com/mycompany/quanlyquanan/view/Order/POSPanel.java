    private void setUpDTable(){
        dTable.setFillsViewportHeight(true);
        dTable.setOpaque(true);
        dTableScroll.getViewport().setBackground(Color.WHITE);
        dTable.setBorder(BorderFactory.createEmptyBorder());
        dTable.setShowHorizontalLines(true);
        dTable.setGridColor(Color.LIGHT_GRAY);
        dTable.setRowSelectionAllowed(true);
        dTable.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        DefaultTableCellRenderer centerRenderer = new DefaultTableCellRenderer();
        centerRenderer.setHorizontalAlignment(SwingConstants.CENTER);
        for (int i = 0; i < dTable.getColumnCount(); i++) {
            dTable.getColumnModel().getColumn(i).setCellRenderer(centerRenderer);
        }

        // Adjust table headers, fill table to the gap
        String[] columnNames = {"No.", "Dish Name", "Quantity", "Price", "Amount" };
        DefaultTableModel model = new DefaultTableModel(columnNames, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // disables editing for all cells
            }
        };
        
        
        for (int i = 0; i < 30; i++) {
            model.addRow(new Object[] { "", "", "", "", "" });
        }
        dTable.setModel(model);
        
        dTable.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                selectedRow = dTable.getSelectedRow();
            }
        });
        
        dTable.addMouseMotionListener(new MouseMotionAdapter() {
            @Override
            public void mouseMoved(MouseEvent e) {
                int row = dTable.rowAtPoint(e.getPoint());
                if (row != -1) {
                    Object dishName = dTable.getValueAt(row, 1); // Column 1: Dish Name
                    if (dishName != null && !dishName.toString().trim().isEmpty()) {
                        dTable.setCursor(Cursor.getPredefinedCursor(Cursor.HAND_CURSOR));
                        return;
                    }
                }
                dTable.setCursor(Cursor.getDefaultCursor());
            }
        });
    }
    
    // Thêm món ăn vào bàn
    private void addDishToTable(Dish d) {
          DefaultTableModel model = (DefaultTableModel) dTable.getModel();

        if (dishMap.containsKey(d)) {
            // Dish already exists — increment quantity
            int quantity = dishMap.get(d) + 1;
            dishMap.put(d, quantity);

            // Find and update the row
            for (int i = 0; i < model.getRowCount(); i++) {
                String name = (String) model.getValueAt(i, 1); // Column 1: Dish Name
                if (name.equals(d.getName())) {
                    model.setValueAt(quantity, i, 2); // Column 2: Quantity
                    model.setValueAt(d.getPrice().multiply(BigDecimal.valueOf(quantity)), i, 4); // Column 4: Amount
                    return;
                }
            }
        } else {
            // New dish — find first empty row
            for (int i = 0; i < model.getRowCount(); i++) {
                String name = (String) model.getValueAt(i, 1);
                if (name == null || name.trim().isEmpty()) {
                    dishMap.put(d, 1);
                    model.setValueAt(i + 1, i, 0); // No.
                    model.setValueAt(d.getName(), i, 1);
                    model.setValueAt(1, i, 2); // Quantity
                    model.setValueAt(d.getPrice(), i, 3); // Price
                    model.setValueAt(d.getPrice(), i, 4); // Amount
                    return;
                }
            }
        }

    }
    
