    // Hiện bảng popup để điều chỉnh quantity
    private void showEditQuantityDialog() {
        int selectedRow = dTable.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn một món để chỉnh sửa.");
            return;
        }

        JDialog dialog = new JDialog((JFrame) SwingUtilities.getWindowAncestor(this), "Chỉnh sửa số lượng", true);
        dialog.setLayout(new GridBagLayout());
        GridBagConstraints gbc = new GridBagConstraints();
        gbc.insets = new Insets(10, 10, 10, 10);
        gbc.fill = GridBagConstraints.HORIZONTAL;

        JLabel label = new JLabel("Nhập số lượng mới:");
        JTextField quantityField = new JTextField(10);

        JButton clearBtn = new JButton("Clear");
        JButton deleteBtn = new JButton("<");
        JButton confirmBtn = new JButton("Confirm");
        
        JPanel numpadPanel = new JPanel(new GridLayout(4, 3, 5, 5));
        String[] digits = { "1", "2", "3", "4", "5", "6", "7", "8", "9", "0" };

        for (String digit : digits) {
            JButton btn = new JButton(digit);
            btn.addActionListener(e -> quantityField.setText(quantityField.getText() + digit));
            numpadPanel.add(btn);
        }


        // Add components
        

        // Label and TextField
        gbc.gridx = 0; gbc.gridy = 0;
        dialog.add(label, gbc);

        gbc.gridx = 1; // assuming you want it beside the label
        dialog.add(quantityField, gbc);

        // Numpad (should come next)
        gbc.gridx = 0; gbc.gridy = 1; gbc.gridwidth = 2;
        dialog.add(numpadPanel, gbc);

        // Clear and Delete buttons
        gbc.gridwidth = 1; // reset gridwidth
        gbc.gridx = 0; gbc.gridy = 2;
        dialog.add(clearBtn, gbc);

        gbc.gridx = 1;
        dialog.add(deleteBtn, gbc);

        // Confirm button
        gbc.gridx = 0; gbc.gridy = 3; gbc.gridwidth = 2;
        dialog.add(confirmBtn, gbc);


        // Button actions
        clearBtn.addActionListener(e -> quantityField.setText(""));

        deleteBtn.addActionListener(e -> {
            String currentText = quantityField.getText();
            if (!currentText.isEmpty()) {
                quantityField.setText(currentText.substring(0, currentText.length() - 1));
            }
        });


        confirmBtn.addActionListener(e -> {
            try {
                int newQty = Integer.parseInt(quantityField.getText());
                if (newQty <= 0) throw new NumberFormatException();

                dTable.setValueAt(newQty, selectedRow, 2); // Quantity column
                double price = Double.parseDouble(dTable.getValueAt(selectedRow, 3).toString());
                dTable.setValueAt(price * newQty, selectedRow, 4); // Amount column

                // Update dishList
                for (Dish dish : dishMap.keySet()) {
                    if (dish.getName().equals(dTable.getValueAt(selectedRow, 1))) {
                        dishMap.put(dish, newQty);
                        break;
                    }
                }

                dialog.dispose();
            } catch (NumberFormatException ex) {
                JOptionPane.showMessageDialog(dialog, "Vui lòng nhập số hợp lệ.");
            }
        });

    dialog.pack();
    dialog.setLocationRelativeTo(this);
    dialog.setVisible(true);
}
    private void removeSelectedDish(){
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn một món để xóa.");
            return;
        }
        
        String dishName = (String) dTable.getValueAt(selectedRow, 1);
        dishMap.entrySet().removeIf(entry -> entry.getKey().getName().equals(dishName));
        
        // Delete row and move up
        DefaultTableModel model = (DefaultTableModel) dTable.getModel();
        int index = 1;
        model.removeRow(selectedRow);
        for (int i = 0; i < model.getRowCount(); i++) {
            String dn = (String) model.getValueAt(i, 1); // Column 1: Dish Name
            if (dn != null && !dn.trim().isEmpty()) {
                model.setValueAt(index++, i, 0); // Column 0: No.
            } else {
                model.setValueAt("", i, 0); // Clear index for empty rows
            }
        }
    }
        
