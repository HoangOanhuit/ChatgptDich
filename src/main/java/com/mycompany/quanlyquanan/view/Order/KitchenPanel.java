    private OrderButton createOrderButton(Order o, JPanel pane, List<Order> canceledList, List<Order> servedList, JTable oDetailTable, String place) {
        OrderButton oBtn = new OrderButton(o, oPanel, canceledList, servedList, oDetailTable, place);
            
            oBtn.addMouseListener(new MouseAdapter() {
                @Override
                public void mousePressed(MouseEvent e) {
                    if (e.getClickCount() == 1 && SwingUtilities.isLeftMouseButton(e)) {
                        addDishToTable(o);
                        currentSelectedPanel = oBtn;
                    }
                }
            });
            
            
        return oBtn;
    }
    
    
    private void addDishToTable(Order o) {
        DefaultTableModel model = (DefaultTableModel) oDetailTable.getModel();

        // Clear existing data but keep row count
        for (int i = 0; i < model.getRowCount(); i++) {
            for (int j = 0; j < model.getColumnCount(); j++) {
                model.setValueAt("", i, j);
            }
        }

        OrderItemController oic = new OrderItemController();
        List<OrderItem> items = oic.getByOrderId(o.getId());
        DishController dc = new DishController();

        int index = 1;
        for (int i = 0; i < items.size() && i < model.getRowCount(); i++) {
            OrderItem oi = items.get(i);
            Dish dish = dc.getById(oi.getDish_id());

            model.setValueAt(index++, i, 0); // "No."
            model.setValueAt(dish.getName(), i, 1); // "Dish Name"
            model.setValueAt(oi.getQuantity(), i, 2); // "Quantity"
            model.setValueAt(o.getStatus(), i, 3);
        }
    }
    
    // Xử lý thông tin từ Redis
    private void startListeningForOIUpdate() {
        JedisPubSub listener = new JedisPubSub() {
            @Override
            public void onMessage(String channel, String message) {
                if ("new_order_channel".equals(channel)) {
                    int oId = Integer.parseInt(message);
                    System.out.println("New order arrive: " + oId);
                    String m = "Đơn hàng " + oId + " mới vừa được tạo! Bạn có muốn xem ngay không?";

                    SwingUtilities.invokeLater(() -> {
                        int choice = JOptionPane.showOptionDialog(
                            null,
                            m,
                            "Thông báo",
                            JOptionPane.YES_NO_OPTION,
                            JOptionPane.INFORMATION_MESSAGE,
                            null,
                            new Object[] { "Xem", "Để sau" },
                            "Xem"
                        );

                        if (choice == JOptionPane.YES_OPTION || currentCatBtn == xnBtn) {
                            handleNewOrder(oId, choice == JOptionPane.YES_OPTION);
                        }

                    });
                }

                if ("cancel_order_channel1".equals(channel)) {
                    int oId = Integer.parseInt(message);
                    System.out.println("Order canceled by restaurant: " + oId);
                    OrderController oc = new OrderController();
                    Order o = oc.getOrderById(oId);
                    String m = "Đơn hàng " + oId + " vừa bị NHÀ HÀNG hủy! Bạn có muốn xem ngay không?";

                    SwingUtilities.invokeLater(() -> {
                        int choice = JOptionPane.showOptionDialog(
                            null,
                            m,
                            "Thông báo",
                            JOptionPane.YES_NO_OPTION,
                            JOptionPane.INFORMATION_MESSAGE,
                            null,
                            new Object[] { "Xem", "Để sau" },
                            "Xem"
                        );

                        
                        handleCancelOrder(o, choice == JOptionPane.YES_OPTION);
                    });
                }
            }
        }; // ✅ Close the listener class here

        RedisSubscriber1 subscriber = new RedisSubscriber1();
        subscriber.subscribe(listener, "cancel_order_channel1", "new_order_channel");
    }
    
    // Handle new Order
    private void handleNewOrder(int orderId, boolean chooseYes) {
        createInitalOrderPanel();
        highlightSelectedButton(xnBtn);
        clearOTable();
        OrderController oc = new OrderController();
        Order o = oc.getOrderById(orderId);
        if (chooseYes)
            addDishToTable(o); 
    }
    
    // Handle cancel order từ nhà hàng
    private void handleCancelOrder(Order o, boolean chooseYes) {
        Component[] components = oPanel.getComponents();

        for (Component comp : components) {
            if (comp instanceof OrderButton) {
                OrderButton ob = (OrderButton) comp;
                if (ob.getOrderId() == o.getId()) {
                    oPanel.remove(ob);
                    break;
                }
            }
        }

        oPanel.revalidate();
        oPanel.repaint();
        canceledList.add(o);
        
        if (chooseYes) {
            highlightSelectedButton(hBtn);
            hBtn.doClick();
            addDishToTable(o);
        } else {
            if(currentCatBtn == hBtn) {
                JPanel oBtn = createOrderButton(o, oPanel, canceledList, servedList, oDetailTable, place);
                oPanel.add(oBtn);
                oPanel.revalidate();
                oPanel.repaint();
            }
        }
    }
    
