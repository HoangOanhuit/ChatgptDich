    // Hiệu chỉnh UI oDetailTable
    private void setUpODTable(){
        oDetailTable.setFillsViewportHeight(true);
        oDetailTable.setOpaque(true);
        oDetailScroll.getViewport().setBackground(Color.WHITE);
        oDetailTable.setBorder(BorderFactory.createEmptyBorder());
        oDetailTable.setShowHorizontalLines(true);
        oDetailTable.setGridColor(Color.LIGHT_GRAY);
        oDetailTable.setRowSelectionAllowed(true);
        oDetailTable.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        DefaultTableCellRenderer centerRenderer = new DefaultTableCellRenderer();
        centerRenderer.setHorizontalAlignment(SwingConstants.CENTER);
        for (int i = 0; i < oDetailTable.getColumnCount(); i++) {
            oDetailTable.getColumnModel().getColumn(i).setCellRenderer(centerRenderer);
        }

        // Adjust table headers, fill table to the gap
        String[] columnNames = {"No.", "Dish Name", "Quantity", "Trạng thái"};
        DefaultTableModel model = new DefaultTableModel(columnNames, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // disables editing for all cells
            }
        };
        
        
        for (int i = 0; i < 30; i++) {
            model.addRow(new Object[] { "", "", "", ""});
        }
        oDetailTable.setModel(model);
        
        oDetailTable.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                selectedRow = oDetailTable.getSelectedRow();
            }
        });
        
        oDetailTable.addMouseMotionListener(new MouseMotionAdapter() {
            @Override
            public void mouseMoved(MouseEvent e) {
                int row = oDetailTable.rowAtPoint(e.getPoint());
                if (row != -1) {
                    Object dishName = oDetailTable.getValueAt(row, 1); // Column 1: Dish Name
                    if (dishName != null && !dishName.toString().trim().isEmpty()) {
                        oDetailTable.setCursor(Cursor.getPredefinedCursor(Cursor.HAND_CURSOR));
                        return;
                    }
                }
                oDetailTable.setCursor(Cursor.getDefaultCursor());
            }
        });
    }
    
