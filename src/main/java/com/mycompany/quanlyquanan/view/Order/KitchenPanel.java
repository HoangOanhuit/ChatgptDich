    private void addCategoryButons(){
        xnBtn = createCatButton("Chờ xác nhận");
        pvBtn = createCatButton("Chờ chế biến");
        ttBtn = createCatButton("Đã xong");
        hBtn = createCatButton("Đã hủy");
        

        // Add all to list for easy access
        categoryButtons.addAll(Arrays.asList(xnBtn, pvBtn, ttBtn, hBtn));

        // Add buttons to panel with spacing
        categoryPanel.add(Box.createVerticalStrut(30));
        categoryPanel.add(xnBtn);
        xnBtn.addActionListener(e -> {
            kConfirm.setEnabled(true);
            kCancel.setEnabled(true);
            kDone.setEnabled(false);
            createInitalOrderPanel();
        });
        categoryPanel.add(Box.createVerticalStrut(30));
        categoryPanel.add(pvBtn);
        pvBtn.addActionListener(e -> {
            kConfirm.setEnabled(false);
            kCancel.setEnabled(true);
            kDone.setEnabled(true);
            createOrderPanelWithStatus("pv");
        });
        
    
        categoryPanel.add(Box.createVerticalStrut(30));
        categoryPanel.add(ttBtn);
        ttBtn.addActionListener(e -> {
            createOrderPanelWithStatus("tt");
            kConfirm.setEnabled(false);
            kCancel.setEnabled(false);
            kDone.setEnabled(false);
        });
        categoryPanel.add(Box.createVerticalStrut(30));
        categoryPanel.add(hBtn);
        hBtn.addActionListener(e -> {
            createOrderPanelHuy();
            kConfirm.setEnabled(false);
            kCancel.setEnabled(false);
            kDone.setEnabled(false);
        });
        

        // Style and add listeners
        for (JButton btn : categoryButtons) {
            btn.setBackground(Color.WHITE);
            btn.setFont(new Font("SansSerif", Font.PLAIN, 14));
            btn.addActionListener(e -> {
                highlightSelectedButton(btn);
                currentCatBtn = btn;
                clearOTable();
            });
        }

        // Set default selected
        highlightSelectedButton(xnBtn);
        currentCatBtn = xnBtn;

        categoryPanel.revalidate();
        categoryPanel.repaint();
    };
    
    private void highlightSelectedButton(JButton selectedBtn) {
        for (JButton btn : categoryButtons) {
            if (btn == selectedBtn) {
                btn.setBackground(new Color(255, 255, 204)); // Highlight
                btn.setFont(btn.getFont().deriveFont(Font.BOLD));
            } else {
                btn.setBackground(Color.WHITE); // Reset
                btn.setFont(btn.getFont().deriveFont(Font.PLAIN));
            }
        }
    }
    
    private void clearOTable(){
        DefaultTableModel model = (DefaultTableModel) oDetailTable.getModel();
        for (int row = 0; row < model.getRowCount(); row++) {
            for (int col = 0; col < model.getColumnCount(); col++) {
                model.setValueAt("", row, col);
            }
        }
    }
    
