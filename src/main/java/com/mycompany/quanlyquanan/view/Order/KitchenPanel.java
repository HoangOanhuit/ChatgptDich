    private void kCancelActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_kCancelActionPerformed
        // TODO add your handling code here:
        if (currentSelectedPanel == null) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn một đơn để hủy.");
            return;
        }
        
        OrderController oc = new OrderController();
        OrderItemController oic = new OrderItemController();
        Order o = oc.getOrderById(currentSelectedPanel.getOrderId());
        o.setStatus("canceled");
        oc.udpate(o);
        List<OrderItem> ol = oic.getByOrderId(o.getId());
        for(OrderItem oi : ol) {
            oi.setStatus("canceled");
            oic.update(oi);
        }
        oPanel.remove(currentSelectedPanel);
        currentSelectedPanel = null;
        oPanel.revalidate();
        oPanel.repaint();
        canceledList.add(o);
        clearOTable();
        new Thread(() -> {
            if (checkTableUse(o)) {
                if(o.getTable_id() != 0) {
                    TableController tc = new TableController();
                    Table t = tc.getTableById(o.getTable_id());
                    t.setStatus("available");
                    tc.updateTable(t);
                } 
            }
        }).start();        
        
        
        if (!isAdmin){
            RedisPublisher.publish("cancel_order_channel", String.valueOf(o.getId()));
        }
        
    }//GEN-LAST:event_kCancelActionPerformed

    private boolean checkTableUse(Order o) {
        if(o.getTable_id() != 0) {
            OrderController oc = new OrderController();
            List<Order> ol = oc.getNPDSUOrder();

            for(Order o1: ol) {
                if (o1.getTable_id() == o.getTable_id())
                    return false;
            }
        }
        
        return true;
    }
    
