    private void loginBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginBtnActionPerformed
        // TODO add your handling code here:
        String userName = juserName.getText().trim();
        String pass = new String(jpass.getPassword());
        
        if (userName.isEmpty() || pass.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ tên đăng nhập và mật khẩu!");
            return;
        }
        
        if (authService.login(userName, pass)) {

            this.dispose();

            // Nhu editt: Mở giao diện chính sau khi đăng nhập thành công
//            HomeFrame homeView = new HomeFrame();
//            homeView.setVisible(true);// Giao diện chính sau đăng nhập
            OpenMenu open = new OpenMenu();
            open.setVisible(true);
        } else {
            JOptionPane.showMessageDialog(this, "Sai tên đăng nhập hoặc mật khẩu");
        }



    }//GEN-LAST:event_loginBtnActionPerformed

