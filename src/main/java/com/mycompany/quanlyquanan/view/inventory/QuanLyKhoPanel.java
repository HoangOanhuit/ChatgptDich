    // Load all materials and update counts
    private void loadAllMaterials() {
        materials = materialService.getAllMaterials();
        refreshTable(materials);
        updateCounts();
    }

    // Refresh table data
    private void refreshTable(List<Material> list) {
        materialTableModel.setRowCount(0);
        for (Material m : list) {
            materialTableModel.addRow(new Object[]{
                m.getId(),
                m.getName(),
                m.getUnit(),
                m.getQuantity(),
                m.getPricePerUnit(),
                m.getThreshold(),
                m.getStockStatus()
            });
        }
        if (!list.isEmpty()) {
            jTable1.setRowSelectionInterval(0, 0);
            selectedMaterial = list.get(0);
            showMaterialDetails(selectedMaterial);
        } else {
            selectedMaterial = null;
            showMaterialDetails(null);
        }
    }

    // Update statistic fields
    private void updateCounts() {
        List<Material> all = materialService.getAllMaterials();
        txtcount.setText(String.valueOf(all.size()));
        txtSapHet.setText(String.valueOf(materialService.getLowStockMaterials().size()));
        txtHetHang.setText(String.valueOf(materialService.getOutOfStockMaterials().size()));

        BigDecimal totalValue = BigDecimal.ZERO;
        for (Material m : all) {
            totalValue = totalValue.add(m.getTotalValue());
        }
        txtTotal.setText(formatCurrency(totalValue));
    }

    // Search materials by keyword
    private void searchMaterials() {
        String keyword = ipSearch.getText().trim();
        if (keyword.isEmpty()) {
            loadAllMaterials();
        } else {
            List<Material> result = materialService.searchMaterials(keyword);
            refreshTable(result);
        }
    }

    // Reset search and show all materials
    private void resetTable() {
        ipSearch.setText("");
        loadAllMaterials();
    }

    // Show low stock materials
    private void showLowStockMaterials() {
        List<Material> low = materialService.getLowStockMaterials();
        refreshTable(low);
    }

    // Show out of stock materials
    private void showOutOfStockMaterials() {
        List<Material> out = materialService.getOutOfStockMaterials();
        refreshTable(out);
    }

    // Display material details on right panel
    private void showMaterialDetails(Material m) {
        if (m == null) {
            txtName.setText("");
            txtID.setText("ID:");
            txtQty.setText("Số lượng:");
            txtThread.setText("Ngưỡng tối thiểu:");
            txtValue.setText("Giá trị:");
            return;
        }
        txtName.setText(m.getName());
        txtID.setText("ID: " + m.getId());
        txtQty.setText("Số lượng: " + m.getQuantity() + " " + m.getUnit());
        txtThread.setText("Ngưỡng tối thiểu: " + m.getThreshold());
        txtValue.setText("Giá trị: " + formatCurrency(m.getTotalValue()));
    }

