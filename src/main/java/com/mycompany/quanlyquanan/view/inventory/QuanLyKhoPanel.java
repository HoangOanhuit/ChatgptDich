       // Initialize table model
    private void initTable() {
        materialTableModel = (DefaultTableModel) jTable1.getModel();
        jTable1.setRowHeight(30);

        DefaultTableCellRenderer stockRenderer = new DefaultTableCellRenderer() {
            @Override
            public Component getTableCellRendererComponent(JTable table, Object value,
                    boolean isSelected, boolean hasFocus, int row, int column) {
                Component c = super.getTableCellRendererComponent(table, value, isSelected, hasFocus, row, column);

                if (!isSelected && (column == 3 || column == 6)) {
                    Object statusObj = table.getValueAt(row, 6);
                    if (statusObj != null) {
                        String status = statusObj.toString().toUpperCase();
                        if (status.contains("HẾT HÀNG")) {
                            c.setForeground(DANGER_COLOR);
                        } else if (status.contains("SẮP HẾT")) {
                            c.setForeground(WARNING_COLOR);
                        } else {
                            c.setForeground(Color.BLACK);
                        }
                    }
                } else if (!isSelected) {
                    c.setForeground(Color.BLACK);
                }
                return c;
            }
        };

        jTable1.getColumnModel().getColumn(3).setCellRenderer(stockRenderer);
        jTable1.getColumnModel().getColumn(6).setCellRenderer(stockRenderer);
    }

    // Setup selection listener to show material details
    private void setupTableSelection() {
        jTable1.getSelectionModel().addListSelectionListener(new ListSelectionListener() {
            @Override
            public void valueChanged(ListSelectionEvent e) {
                if (!e.getValueIsAdjusting()) {
                    int row = jTable1.getSelectedRow();
                    if (row >= 0 && row < materials.size()) {
                        selectedMaterial = materials.get(row);
                        showMaterialDetails(selectedMaterial);
                    }
                }
            }
        });
    }
    // Make statistic text fields transparent
